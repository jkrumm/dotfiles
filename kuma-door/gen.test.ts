import { afterEach, expect, test } from "bun:test"
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { render } from "./gen"
import type { Registry } from "./registry"

const dirs: string[] = []
const tmp = () => { const d = mkdtempSync(join(tmpdir(), "kuma-gen-")); dirs.push(d); return d }
afterEach(() => { for (const d of dirs.splice(0)) rmSync(d, { recursive: true, force: true }) })

const registry: Registry = {
  port: 8795,
  services: [
    { name: "argo", url: "http://127.0.0.1:7737/api/health", title: "Argo" },
    { name: "slow-one", url: "http://127.0.0.1:9000/", title: "Slow One", interval: 300 },
  ],
}

const GOLDEN = `# GENERATED by dotfiles/kuma-door/gen.ts from kuma-door/registry.json — do not edit.
# Regenerate with \`make kuma-door-gen\` (dotfiles repo, on the mini).
#
# The host (\${MINI_TAILSCALE_HOST}, substituted by sync.py) is the mini's MagicDNS name, from
# 1Password op://homelab/config/MINI_TAILSCALE_HOST, never written into git. The door's certificate
# is issued for that name, so TLS validates normally.

groups:
  - name: Local
    monitors:
      - name: "Mac mini door"
        type: group
        interval: 200
        monitors:
          - name: "Argo - Door"
            type: http
            url: "https://\${MINI_TAILSCALE_HOST}:8795/h/argo"
            interval: 120
            maxretries: 2
            retry_interval: 60
            accepted_statuscodes: ["200-299"]

          - name: "Slow One - Door"
            type: http
            url: "https://\${MINI_TAILSCALE_HOST}:8795/h/slow-one"
            interval: 300
            maxretries: 2
            retry_interval: 60
            accepted_statuscodes: ["200-299"]
`

test("render matches the golden fragment and leaves the placeholder unresolved", () => {
  const out = render(registry)
  expect(out).toBe(GOLDEN)
  expect(out).toContain("${MINI_TAILSCALE_HOST}")
})

test("render is deterministic", () => {
  expect(render(registry)).toBe(render(structuredClone(registry)))
})

const gen = (...args: string[]) => Bun.spawnSync(["bun", join(import.meta.dir, "gen.ts"), ...args], { stderr: "pipe", stdout: "pipe" })

test("--out writes, --check passes on it and fails on a changed file or a missing one", () => {
  const file = join(tmp(), "monitors.yaml")
  expect(gen("--out", file).exitCode).toBe(0)
  expect(readFileSync(file, "utf8")).toBe(render(JSON.parse(readFileSync(join(import.meta.dir, "registry.json"), "utf8"))))
  expect(gen("--check", file).exitCode).toBe(0)

  writeFileSync(file, `${readFileSync(file, "utf8")}# drift\n`)
  const stale = gen("--check", file)
  expect(stale.exitCode).toBe(1)
  expect(stale.stderr.toString()).toContain("make kuma-door-gen")

  expect(gen("--check", join(tmp(), "absent.yaml")).exitCode).toBe(1)
})

test("flags without a file or unknown flags are usage errors", () => {
  expect(gen("--out").exitCode).toBe(2)
  expect(gen("--bogus").exitCode).toBe(2)
})
