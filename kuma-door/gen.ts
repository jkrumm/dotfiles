#!/usr/bin/env bun
// kuma-door gen — prints the Uptime Kuma monitors for registry.json as a YAML fragment in the
// format of homelab's uptime-kuma/sync.py `--extra-config`. Deterministic: services in registry
// order. Regenerate with `make kuma-door-gen`.
//   gen.ts                 print to stdout
//   gen.ts --out <file>    write the fragment to <file>
//   gen.ts --check <file>  exit 1 with a message if <file> differs from the fragment
import { existsSync, readFileSync, writeFileSync } from "node:fs"
import { loadRegistry, type Registry } from "./registry"

const HEADER = `# GENERATED by dotfiles/kuma-door/gen.ts from kuma-door/registry.json — do not edit.
# Regenerate with \`make kuma-door-gen\` (dotfiles repo, on the mini).
#
# The host (\${MINI_TAILSCALE_HOST}, substituted by sync.py) is the mini's MagicDNS name, from
# 1Password op://homelab/config/MINI_TAILSCALE_HOST, never written into git. The door's certificate
# is issued for that name, so TLS validates normally.
`

const DEFAULT_INTERVAL = 120

export function render(registry: Registry): string {
  const q = (s: string) => JSON.stringify(s) // a JSON string is a valid YAML double-quoted scalar
  const monitors = registry.services.map(
    (s) => `          - name: ${q(`${s.title} - Door`)}
            type: http
            url: ${q(`https://\${MINI_TAILSCALE_HOST}:${registry.port}/h/${s.name}`)}
            interval: ${s.interval ?? DEFAULT_INTERVAL}
            maxretries: 2
            retry_interval: 60
            accepted_statuscodes: ["200-299"]
`,
  )
  return `${HEADER}
groups:
  - name: Local
    monitors:
      - name: "Mac mini door"
        type: group
        interval: 200
        monitors:
${monitors.join("\n")}`
}

if (import.meta.main) {
  const args = process.argv.slice(2)
  const flag = args[0]
  const file = args[1]
  if ((flag === "--out" || flag === "--check") && !file) {
    process.stderr.write(`kuma-door gen: ${flag} needs a file\n`)
    process.exit(2)
  }
  if (flag !== undefined && flag !== "--out" && flag !== "--check") {
    process.stderr.write("usage: gen.ts [--out <file> | --check <file>]\n")
    process.exit(2)
  }
  let out: string
  try {
    out = render(loadRegistry())
  } catch (err) {
    process.stderr.write(`kuma-door gen: ${err instanceof Error ? err.message : String(err)}\n`)
    process.exit(1)
  }
  if (flag === "--out") {
    writeFileSync(file!, out)
  } else if (flag === "--check") {
    if (!existsSync(file!) || readFileSync(file!, "utf8") !== out) {
      process.stderr.write(`kuma-door gen: ${file} is stale or missing — run: make kuma-door-gen\n`)
      process.exit(1)
    }
  } else {
    process.stdout.write(out)
  }
}
