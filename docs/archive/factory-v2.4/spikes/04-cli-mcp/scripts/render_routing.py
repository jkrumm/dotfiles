#!/usr/bin/env python3
"""Render the AGENTS.md gateway-routing block from the CLIs' own `--help`, and check it for drift.

The command surface (signatures, one-line descriptions, exit codes) is never typed by hand: it is
parsed from `<bin> --help` of each CLI named in routing.config.json. The config only says WHICH
subcommands to expose and carries one static policy sentence, so a renamed flag or a removed
command changes the render and the drift check fails.

  render_routing.py                       print the block
  render_routing.py --write AGENTS.md     replace the block between the markers (append if absent)
  render_routing.py --check AGENTS.md     re-render and diff against the file: exit 0 = in sync,
                                          1 = drift (unified diff on stdout), 2 = cannot render

Help format this parser understands (agw, research and mailgw all follow it):
  line 1:  `<name> — <purpose>`; a `Usage:` section of `  <bin> <command> <args>[   <description>]`
  lines (two-space indent; deeper indent = continuation, a flag-looking continuation extends the
  signature, prose extends the description); and an `Exit codes:` line (inline or on the next line).
"""

from __future__ import annotations

import argparse
import difflib
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

BEGIN = "<!-- gateway-routing:begin (generated by render_routing.py from each CLI's --help; edit the CLIs or routing.config.json, never this block) -->"
END = "<!-- gateway-routing:end -->"
CONFIG = Path(__file__).with_name("routing.config.json")


def die(message: str) -> None:
    """Cannot render (as opposed to drift): exit 2, so a CI caller can tell the two apart."""
    print(f"render_routing: {message}", file=sys.stderr)
    sys.exit(2)


def read_help(binary: str) -> str:
    exe = shutil.which(binary) or str(Path(__file__).with_name(binary))  # scratch CLIs ship next to this script
    out = subprocess.run([exe, "--help"], capture_output=True, text=True, check=False)
    text = out.stdout or out.stderr
    if not text.strip():
        die(f"`{binary} --help` printed nothing (exit {out.returncode})")
    return text


def parse_help(text: str, binary: str) -> dict:
    lines = text.splitlines()
    purpose = lines[0].split(" — ", 1)[1].strip() if " — " in lines[0] else lines[0].strip()
    entries: list[dict] = []
    in_usage = False
    for raw in lines[1:]:
        if raw.strip() == "Usage:":
            in_usage = True
            continue
        if in_usage and not raw.strip():
            break
        if not in_usage:
            continue
        indent = len(raw) - len(raw.lstrip())
        if indent <= 2 and raw.strip().startswith(binary):
            parts = re.split(r"\s{3,}", raw.strip(), maxsplit=1)
            entries.append({"sig": parts[0], "desc": parts[1] if len(parts) > 1 else ""})
        elif entries and indent > 2:
            cont = raw.strip()
            key = "sig" if cont[0] in "[<-\"" else "desc"
            entries[-1][key] = (entries[-1][key] + " " + cont).strip()
    exit_codes = ""
    for i, raw in enumerate(lines):
        if "Exit codes:" in raw:
            tail = raw.split("Exit codes:", 1)[1].strip()
            exit_codes = tail or (lines[i + 1].strip() if i + 1 < len(lines) else "")
            break
    return {"purpose": purpose, "entries": entries, "exit": exit_codes.rstrip(".")}


def command_of(sig: str, binary: str) -> str:
    rest = sig[len(binary):].split()
    return rest[0] if rest else ""


def render(config: dict) -> str:
    out = [BEGIN, config["intro"]]
    for cli in config["clis"]:
        binary = cli["bin"]
        parsed = parse_help(read_help(binary), binary)
        head = f"`{binary}` — {parsed['purpose']}"
        out.append(head + (f" (exit {parsed['exit']})" if parsed["exit"] else ""))
        by_cmd = {command_of(e["sig"], binary): e for e in parsed["entries"]}
        missing = [c for c in cli["expose"] if c not in by_cmd]
        if missing:
            die(f"`{binary} --help` has no usage line for: {', '.join(missing)}")
        groups: dict[str, list[dict]] = {}  # identical argument tail -> one merged line (status|wait <jobId>)
        for cmd in cli["expose"]:
            e = by_cmd[cmd]
            tail = e["sig"][len(binary):].split(None, 1)[1] if len(e["sig"][len(binary):].split(None, 1)) > 1 else ""
            groups.setdefault(tail, []).append({"cmd": cmd, **e})
        for tail, items in groups.items():
            if len(items) == 1:
                e = items[0]
                out.append(f"  {e['sig']}" + (f"   {e['desc']}" if e["desc"] else ""))
            else:
                names = "|".join(i["cmd"] for i in items)
                descs = "; ".join(i["desc"] for i in items if i["desc"])
                out.append(f"  {binary} {names} {tail}".rstrip() + (f"   {descs}" if descs else ""))
    out.append(END)
    if len(out) > config["max_lines"]:
        die(f"block is {len(out)} lines, budget is {config['max_lines']}")
    return "\n".join(out) + "\n"


def extract(text: str) -> str | None:
    m = re.search(re.escape(BEGIN.split(" (")[0]) + r".*?\n.*?" + re.escape(END) + r"\n?", text, re.S)
    return m.group(0) if m else None


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--write", metavar="FILE")
    g.add_argument("--check", metavar="FILE")
    ap.add_argument("--config", default=str(CONFIG))
    a = ap.parse_args()
    block = render(json.loads(Path(a.config).read_text()))
    if a.write:
        p = Path(a.write)
        current = p.read_text() if p.exists() else ""
        old = extract(current)
        p.write_text(current.replace(old, block) if old else (current.rstrip("\n") + "\n\n" if current else "") + block)
        print(f"wrote {len(block.splitlines())}-line block to {p}")
    elif a.check:
        current = extract(Path(a.check).read_text())
        if current is None:
            print(f"drift-check: no gateway-routing block in {a.check}", file=sys.stderr)
            return 2
        if current == block:
            print(f"no drift: {a.check} matches the CLIs' --help ({len(block.splitlines())} lines)")
            return 0
        sys.stdout.writelines(difflib.unified_diff(current.splitlines(True), block.splitlines(True), "committed", "rendered"))
        print("\ndrift: re-run `render_routing.py --write` and commit the result", file=sys.stderr)
        return 1
    else:
        sys.stdout.write(block)
    return 0


if __name__ == "__main__":
    sys.exit(main())
