// Builds specs/research.openapi.json for research-gateway's REST routes WITHOUT touching that
// repo. Only env-free modules are imported (src/agent/schema.ts imports nothing but zod).
// `ResearchSubmit` and the three response wrappers are declared inline in src/routes/research.ts,
// which imports src/env.ts, so they are RE-DECLARED below. `--check` compares the route table in
// research.ts (method + path + declared statuses) with the spec to catch the cheap kind of drift.
//
// Run: node gen-openapi.ts [--check]     (or: bun gen-openapi.ts)

import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { z } from 'zod'
import { JobLiveFields, JobStatus, ResearchInput, ResearchReport } from '../../../../../../research-gateway/src/agent/schema.ts'

const here = dirname(fileURLToPath(import.meta.url))
const RG = '/Users/jkrumm/SourceRoot/research-gateway'
const ROUTE_FILE = join(RG, 'src/routes/research.ts')
const OUT = join(here, 'specs/research.openapi.json')

// ── Re-declared from src/routes/research.ts (drift risk, see REPORT.md) ──────────────────────
const ResearchSubmit = ResearchInput.extend({
  idempotencyKey: z
    .string()
    .min(1)
    .max(200)
    .optional()
    .describe(
      'Optional caller-supplied key (1..200 chars). Retrying a submit with the same key returns the original job instead of starting a second one.',
    ),
})
const SubmitResponse = z.object({ jobId: z.string(), status: z.string(), warnings: z.array(z.string()).optional() })
const StatusResponse = z.object({
  status: JobStatus, // the route declares z.string(); the enum is the documented truth
  ...JobLiveFields,
  result: ResearchReport.optional(),
  error: z.string().optional(),
})
const CancelResponse = z.object({ jobId: z.string(), status: z.string() })
const ErrorBody = z.object({ error: z.string() })

const schemaOf = (s: z.ZodType, io: 'input' | 'output') => {
  const { $schema: _drop, ...rest } = z.toJSONSchema(s, { io }) as Record<string, unknown>
  return rest
}
const json = (s: z.ZodType, io: 'input' | 'output') => ({ content: { 'application/json': { schema: schemaOf(s, io) } } })
const errors = (...codes: [number, string][]) =>
  Object.fromEntries(codes.map(([c, d]) => [String(c), { description: d, ...json(ErrorBody, 'output') }]))

const jobIdParam = {
  name: 'jobId',
  in: 'path',
  required: true,
  description: 'Job id returned by the submit call.',
  schema: { type: 'string', minLength: 1 },
}
const TERMINAL = ['done', 'error', 'cancelled']

export function buildSpec() {
  return {
    openapi: '3.1.0',
    info: {
      title: 'research-gateway REST door (spike-generated)',
      version: '0.0.0-spike',
      description: `Generated by spikes/07-stations/cli-runner/gen-openapi.ts from research-gateway@${gitSha()} (src/agent/schema.ts imported, src/routes/research.ts re-declared).`,
      'x-source': { repo: 'research-gateway', sha: gitSha(), routeFile: 'src/routes/research.ts' },
    },
    servers: [{ url: 'http://localhost:7780' }],
    components: { securitySchemes: { BearerAuth: { type: 'http', scheme: 'bearer' } } },
    security: [{ BearerAuth: [] }],
    paths: {
      '/research': {
        post: {
          operationId: 'researchSubmit',
          tags: ['Research'],
          summary: 'Submit a research query',
          description:
            'Enqueues an agentic research job and returns a jobId immediately. Poll GET /research/{jobId} to check status and retrieve the result.',
          requestBody: { required: true, ...json(ResearchSubmit, 'input') },
          responses: {
            '200': { description: 'Job accepted', ...json(SubmitResponse, 'output') },
            ...errors([429, 'Queue full (Retry-After set)'], [503, 'Draining or memory pressure']),
          },
          'x-cli': {
            command: ['research', 'run'],
            positional: ['query'],
            defaultFormat: 'plain',
            plainField: 'result.report',
            mutating: true,
            job: {
              statusOperationId: 'researchStatus',
              idField: 'jobId',
              statusField: 'status',
              terminal: TERMINAL,
              successStatus: 'done',
              resume: { command: ['research', 'wait'] },
            },
          },
        },
      },
      '/research/{jobId}': {
        get: {
          operationId: 'researchStatus',
          tags: ['Research'],
          summary: 'Poll a research job',
          description:
            'Current status of a research job plus live fields. When status is done, result holds the cited report; when error or cancelled, error says why.',
          parameters: [jobIdParam],
          responses: {
            '200': { description: 'Current job state', ...json(StatusResponse, 'output') },
            ...errors([404, 'Unknown or expired job id']),
          },
          'x-cli': {
            command: ['research', 'status'],
            positional: ['jobId'],
            defaultFormat: 'plain',
            plainField: 'result.report',
            mutating: false,
          },
        },
        delete: {
          operationId: 'researchCancel',
          tags: ['Research'],
          summary: 'Cancel a research job',
          description:
            'Cancels a queued or running job. Idempotent: an already-terminal job is returned with its status unchanged.',
          parameters: [jobIdParam],
          responses: {
            '200': { description: 'Job after cancel', ...json(CancelResponse, 'output') },
            ...errors([404, 'Unknown or expired job id'], [409, 'Job runs on another replica']),
          },
          'x-cli': { command: ['research', 'cancel'], positional: ['jobId'], defaultFormat: 'plain', mutating: true },
        },
      },
    },
  }
}

function gitSha(): string {
  try {
    return execFileSync('git', ['-C', RG, 'rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim()
  } catch {
    return 'unknown'
  }
}

/** Route table of research.ts as text: [`POST /`, `GET /:jobId`, …] and the declared statuses. */
function routeTable(src: string): { routes: string[]; statuses: number[] } {
  const routes = [...src.matchAll(/\.(post|get|delete|put|patch)\(\s*'([^']+)'/g)].map((m) => `${m[1]!.toUpperCase()} ${m[2]}`)
  const statuses = [...src.matchAll(/^\s+(\d{3}): z\./gm)].map((m) => Number(m[1]))
  return { routes, statuses }
}

function check(spec: ReturnType<typeof buildSpec>): string[] {
  const problems: string[] = []
  const { routes, statuses } = routeTable(readFileSync(ROUTE_FILE, 'utf8'))
  const specRoutes = Object.entries(spec.paths).flatMap(([p, ops]) =>
    Object.keys(ops).map((m) => `${m.toUpperCase()} ${p === '/research' ? '/' : p.replace('/research/', '/').replace(/\{(\w+)\}/g, ':$1')}`),
  )
  for (const r of routes) if (!specRoutes.includes(r)) problems.push(`route in research.ts missing from spec: ${r}`)
  for (const r of specRoutes) if (!routes.includes(r)) problems.push(`route in spec not in research.ts: ${r}`)
  const specStatuses = Object.values(spec.paths).flatMap((ops) =>
    Object.values(ops).flatMap((op) => Object.keys((op as { responses: object }).responses).map(Number)),
  )
  for (const s of statuses) if (!specStatuses.includes(s)) problems.push(`status ${s} declared in research.ts missing from spec`)
  return problems
}

if (import.meta.main) {
  const spec = buildSpec()
  if (process.argv.includes('--check')) {
    const problems = check(spec)
    const onDisk = readFileSync(OUT, 'utf8')
    if (onDisk !== JSON.stringify(spec, null, 2) + '\n') problems.push('specs/research.openapi.json is stale (re-run gen)')
    for (const p of problems) console.error(p)
    console.log(problems.length === 0 ? 'in sync' : `${problems.length} drift problem(s)`)
    process.exitCode = problems.length === 0 ? 0 : 1
  } else {
    writeFileSync(OUT, JSON.stringify(spec, null, 2) + '\n')
    const problems = check(spec)
    console.log(`wrote ${OUT}${problems.length ? ` (drift: ${problems.join('; ')})` : ''}`)
  }
}
