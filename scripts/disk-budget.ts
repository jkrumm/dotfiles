#!/usr/bin/env bun
// disk-budget — the mini's disk budget as data, measured daily (docs/disk.md).
//
//   disk-budget.ts check [--file F]            measure every row with du -xk, write the status file, file one factory
//                                              signal per row over its cap (and per uncovered path over unknown_gib)
//   disk-budget.ts lint  [--file F] [--doc D]  static: the table is valid, its caps plus the system share stay under
//                                              max_commit_pct of the volume, docs/disk.md carries the rendered table
//   disk-budget.ts table [--write] [--file F] [--doc D]   the table as markdown; --write replaces the block in the doc
//
// The budget is config/mini/disk-budget.yaml: one row per path with owner (a repo), cap_gib, class and enforced_by. The
// check runs as a jobrun job (com.jkrumm.disk-budget). A row over its cap does not fail the job: it files ONE signal on the
// owner and stamps it, so the next run stays quiet until the row has been under cap again or REFILE_DAYS have passed. The job
// fails on what only a human edit repairs: a table that over-commits the volume, a signal the factory refused for the owner
// and for dotfiles alike. A row whose du stalls twice is reported unmeasured (measured_gib null) for that run: a stall is transient.
//
// Environment (tests and tools): DISK_BUDGET_FILE, DISK_BUDGET_STATE_DIR (default ~/.local/state/disk-budget),
// DISK_BUDGET_FACTORY (default factory), DISK_BUDGET_DOC. HOME is read as is.
import { spawnSync } from "node:child_process"
import { existsSync, mkdirSync, readFileSync, renameSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"

const DOTFILES = resolve(import.meta.dir, "..")
const DEFAULT_FILE = join(DOTFILES, "config", "mini", "disk-budget.yaml")
const DEFAULT_DOC = join(DOTFILES, "docs", "disk.md")
const KIB_PER_GIB = 1048576
const REFILE_DAYS = 14
const SCAN_BUDGET_MS = 1_500_000
const ROW_TIMEOUT_MS = 300_000
const BLOCK_START = "<!-- disk-budget:table (generated by scripts/disk-budget.ts table --write; edit config/mini/disk-budget.yaml) -->"
const BLOCK_END = "<!-- /disk-budget:table -->"
export const CLASSES = ["data", "cache", "build", "history"] as const
type Class = (typeof CLASSES)[number]

export interface Row {
  path: string
  owner: string
  cap_gib: number
  class: Class
  enforced_by: string
}
export interface Budget {
  volume: string
  volume_gib: number
  system_gib: number
  max_commit_pct: number
  unknown_gib: number
  scan_depth: number
  scan: string[]
  rows: Row[]
}

const home = () => process.env.HOME ?? ""
export const expand = (p: string) => (p === "~" ? home() : p.startsWith("~/") ? join(home(), p.slice(2)) : p)
const gib = (kib: number) => kib / KIB_PER_GIB
export const fmt = (n: number) => (n >= 10 ? n.toFixed(1) : n >= 0.1 ? n.toFixed(2) : n.toFixed(4))

export function parseBudget(text: string): { budget: Budget | null; errors: string[] } {
  const errors: string[] = []
  let doc: any
  try {
    doc = Bun.YAML.parse(text)
  } catch (e) {
    return { budget: null, errors: [`unparseable YAML: ${(e as Error).message}`] }
  }
  const num = (k: string, min: number) => {
    const v = doc?.[k]
    if (typeof v !== "number" || !(v > min)) errors.push(`${k} must be a number > ${min}`)
    return Number(v)
  }
  const volume = typeof doc?.volume === "string" && doc.volume.startsWith("/") ? doc.volume : (errors.push("volume must be an absolute path"), "")
  const budget: Budget = {
    volume,
    volume_gib: num("volume_gib", 0),
    system_gib: num("system_gib", -1),
    max_commit_pct: num("max_commit_pct", 0),
    unknown_gib: num("unknown_gib", 0),
    scan_depth: num("scan_depth", 0),
    scan: Array.isArray(doc?.scan) ? doc.scan.map(String) : (errors.push("scan must be a list of paths"), []),
    rows: [],
  }
  if (budget.max_commit_pct > 100) errors.push("max_commit_pct must be at most 100")
  if (!Array.isArray(doc?.rows) || doc.rows.length === 0) errors.push("rows must be a non-empty list")
  const seen = new Set<string>()
  for (const [i, r] of (Array.isArray(doc?.rows) ? doc.rows : []).entries()) {
    const at = `rows[${i}]${typeof r?.path === "string" ? ` (${r.path})` : ""}`
    if (typeof r?.path !== "string" || !/^(~|\/)/.test(r.path) || r.path.length < 2 || r.path.endsWith("/")) { errors.push(`${at}: path must be ~/… or an absolute path without a trailing slash`); continue }
    if (seen.has(r.path)) errors.push(`${at}: duplicate path`)
    seen.add(r.path)
    if (typeof r.owner !== "string" || !/^[A-Za-z0-9._-]+$/.test(r.owner)) errors.push(`${at}: owner must be a repo name`)
    if (typeof r.cap_gib !== "number" || !(r.cap_gib > 0)) errors.push(`${at}: cap_gib must be a number > 0`)
    if (!CLASSES.includes(r.class)) errors.push(`${at}: class must be one of ${CLASSES.join(", ")}`)
    if (typeof r.enforced_by !== "string" || r.enforced_by.trim() === "") errors.push(`${at}: enforced_by must say what holds the cap`)
    budget.rows.push({ path: r.path, owner: String(r.owner), cap_gib: Number(r.cap_gib), class: r.class, enforced_by: String(r.enforced_by) })
  }
  // A row inside another row would be counted twice, in the sum and in the measurement.
  for (const a of budget.rows) for (const b of budget.rows) if (a !== b && b.path.startsWith(a.path + "/")) errors.push(`${b.path} is inside ${a.path}: a path belongs to one row`)
  return { budget: errors.length ? null : budget, errors }
}

export const commit = (b: Budget, volumeGib = b.volume_gib) => {
  const caps = b.rows.reduce((s, r) => s + r.cap_gib, 0)
  return { caps, system: b.system_gib, total: caps + b.system_gib, limit: (b.max_commit_pct / 100) * volumeGib, volumeGib }
}

export function renderTable(b: Budget): string {
  const c = commit(b)
  const rows = b.rows.map((r) => `| \`${r.path}\` | ${r.owner} | ${r.cap_gib} | ${r.class} | ${r.enforced_by} |`)
  return [
    "| Path | Owner | Cap GiB | Class | Held by |",
    "|-|-|-|-|-|",
    ...rows,
    "",
    `Caps ${fmt(c.caps)} + system ${fmt(c.system)} = ${fmt(c.total)} GiB; the limit is ${b.max_commit_pct} % of ${b.volume_gib} GiB = ${fmt(c.limit)} GiB.`,
  ].join("\n")
}

function docBlock(doc: string): { before: string; block: string; after: string } | null {
  const s = doc.indexOf(BLOCK_START)
  const e = doc.indexOf(BLOCK_END)
  if (s < 0 || e < s) return null
  return { before: doc.slice(0, s), block: doc.slice(s + BLOCK_START.length, e).trim(), after: doc.slice(e + BLOCK_END.length) }
}

export function lint(file: string, docFile: string): string[] {
  const { budget, errors } = parseBudget(readFileSync(file, "utf8"))
  if (!budget) return errors
  const c = commit(budget)
  if (c.total > c.limit) errors.push(`the table over-commits the volume: caps ${fmt(c.caps)} + system ${fmt(c.system)} = ${fmt(c.total)} GiB > ${fmt(c.limit)} GiB (${budget.max_commit_pct} % of ${budget.volume_gib}); lower a cap`)
  if (existsSync(docFile)) {
    const parts = docBlock(readFileSync(docFile, "utf8"))
    if (!parts) errors.push(`${docFile} has no disk-budget:table block`)
    else if (parts.block !== renderTable(budget)) errors.push(`${docFile} carries a stale table: run bun scripts/disk-budget.ts table --write`)
  }
  return errors
}

// ---- measuring ----

interface Du { ok: boolean; sizes: Map<string, number> }

function du(args: string[], timeoutMs: number): Du {
  const r = spawnSync("nice", ["-n", "19", "du", "-xk", ...args], { encoding: "utf8", maxBuffer: 512 * 1024 * 1024, timeout: timeoutMs })
  const sizes = new Map<string, number>()
  // du exits non-zero on every unreadable directory (TCC) and still prints the rest; only a timeout or a spawn error is a failure.
  if (r.error || typeof r.stdout !== "string") return { ok: false, sizes }
  for (const line of r.stdout.split("\n")) {
    const tab = line.indexOf("\t")
    if (tab > 0) sizes.set(line.slice(tab + 1), Number(line.slice(0, tab)))
  }
  return { ok: sizes.size > 0, sizes }
}

export function findUnknown(sizes: Map<string, number>, rows: Row[], minKib: number): [string, number][] {
  const rowPaths = rows.map((r) => expand(r.path))
  const uncovered = [...sizes].filter(([p, kib]) => kib >= minKib && !rowPaths.some((r) => p === r || p.startsWith(r + "/")) && !rowPaths.some((r) => r.startsWith(p + "/")))
  // The shallowest only: a path whose ancestor is already reported adds nothing.
  return uncovered.filter(([p]) => !uncovered.some(([q]) => p.startsWith(q + "/"))).sort((a, b) => b[1] - a[1])
}

// A stalled du is transient (a healthy ~/Library takes under a minute), so a row gets a second attempt before it counts as unmeasured.
function measureRow(path: string): number | undefined {
  for (let attempt = 0; attempt < 2; attempt++) {
    const kib = du(["-s", path], ROW_TIMEOUT_MS).sizes.get(path)
    if (kib !== undefined) return kib
  }
  return undefined
}

function liveVolume(volume: string): { sizeGib: number; usedGib: number; freeGib: number; pct: number } | null {
  const r = spawnSync("df", ["-k", volume], { encoding: "utf8" })
  const f = r.stdout?.split("\n")[1]?.trim().split(/\s+/)
  if (r.status !== 0 || !f || f.length < 4) return null
  const [size, used, avail] = [Number(f[1]), Number(f[2]), Number(f[3])]
  return { sizeGib: gib(size), usedGib: gib(used), freeGib: gib(avail), pct: Math.round((used / (used + avail)) * 100) }
}

// ---- signals ----

interface State { filed: Record<string, { at: string; measured_gib: number; cap_gib: number }> }
const readJson = <T>(p: string, fallback: T): T => {
  try { return JSON.parse(readFileSync(p, "utf8")) as T } catch { return fallback }
}
function writeAtomic(p: string, text: string) {
  mkdirSync(dirname(p), { recursive: true })
  const tmp = `${p}.${process.pid}.tmp`
  writeFileSync(tmp, text)
  renameSync(tmp, p)
}

function fileSignal(factory: string, repo: string, title: string, text: string): boolean {
  const r = spawnSync(factory, ["signal", "file", "--from", "agent:dotfiles", "--repo", repo, "--title", title, "--text", text], { encoding: "utf8", timeout: 60_000 })
  if (r.status !== 0) console.error(`signal to ${repo} refused: ${(r.stderr || r.stdout || r.error?.message || "").trim().slice(0, 300)}`)
  return r.status === 0
}

// ---- the check ----

function check(file: string): number {
  const { budget, errors } = parseBudget(readFileSync(file, "utf8"))
  if (!budget) {
    for (const e of errors) console.error(`disk-budget: ${e}`)
    return 1
  }
  const stateDir = process.env.DISK_BUDGET_STATE_DIR ?? join(home(), ".local", "state", "disk-budget")
  const factory = process.env.DISK_BUDGET_FACTORY ?? "factory"
  const now = new Date()
  let failures = 0

  const vol = liveVolume(budget.volume)
  const volumeGib = vol ? Math.min(budget.volume_gib, vol.sizeGib) : budget.volume_gib
  const c = commit(budget, volumeGib)
  const overCommitted = c.total > c.limit
  if (vol) console.log(`disk-budget: ${budget.volume} ${fmt(vol.sizeGib)} GiB, ${fmt(vol.usedGib)} used (${vol.pct} %), ${fmt(vol.freeGib)} free`)
  console.log(`disk-budget: caps ${fmt(c.caps)} + system ${fmt(c.system)} = ${fmt(c.total)} GiB of ${fmt(c.limit)} allowed (${budget.max_commit_pct} % of ${fmt(volumeGib)}): ${overCommitted ? "OVER-COMMITTED" : "ok"}`)
  if (overCommitted) failures++

  const sizes = new Map<string, number>()
  let scanOk = true
  const scanDeadline = Date.now() + SCAN_BUDGET_MS
  for (const root of budget.scan) {
    const left = scanDeadline - Date.now()
    if (left <= 0) {
      scanOk = false
      console.error(`disk-budget: the scan budget (${SCAN_BUDGET_MS / 60_000} min, shared by all roots) is spent before ${root}; uncovered paths are not checked this run`)
      break
    }
    const r = du(["-d", String(budget.scan_depth), expand(root)], left)
    // A failed scan only loses the uncovered-path check for this run: every row is then measured on its own below.
    if (!r.ok && existsSync(expand(root))) {
      scanOk = false
      console.error(`disk-budget: the scan of ${root} failed; its rows are measured one by one, uncovered paths are not checked this run`)
    }
    for (const [p, kib] of r.sizes) sizes.set(p, kib)
  }

  const state = readJson<State>(join(stateDir, "state.json"), { filed: {} })
  const filed: State["filed"] = {}
  const keep = (key: string) => { if (state.filed[key]) filed[key] = state.filed[key] }
  const due = (key: string) => {
    const at = state.filed[key]?.at
    return !at || now.getTime() - Date.parse(at) > REFILE_DAYS * 86_400_000
  }
  let nFiled = 0
  // Without a scan there is no uncovered-path check: its signals stay on record, so the next run does not file them again.
  if (!scanOk) for (const key of Object.keys(state.filed)) if (key.startsWith("unknown:")) keep(key)

  const rows = budget.rows.map((row) => {
    const path = expand(row.path)
    let kib = sizes.get(path)
    let present = existsSync(path)
    if (kib === undefined && present) {
      kib = measureRow(path)
      if (kib === undefined) {
        console.error(`disk-budget: could not measure ${row.path} (du stalled twice); no value this run, not a failure`)
        keep(row.path)
        return { path: row.path, owner: row.owner, class: row.class, enforced_by: row.enforced_by, cap_gib: row.cap_gib, measured_gib: null, over: false, present, signal: null }
      }
    }
    if (!present) kib = 0
    const measured = gib(kib ?? 0)
    const over = kib !== undefined && measured > row.cap_gib
    let signal: "filed" | "open" | null = null
    if (over) {
      keep(row.path)
      if (due(row.path)) {
        const title = `disk budget: ${row.path} is ${fmt(measured)} GiB, cap ${row.cap_gib} GiB (${row.owner})`
        const text = [
          `${row.path} measures ${fmt(measured)} GiB (du -xk) against a cap of ${row.cap_gib} GiB in the mini's disk budget (config/mini/disk-budget.yaml in dotfiles, docs/disk.md). Class ${row.class}; held by: ${row.enforced_by}.`,
          vol ? `The Data volume is ${vol.pct} % used.` : "",
          "Bring the path under its cap, or, if it needs more, say so in a signal on dotfiles: a cap changes by editing its row, and the caps plus the system share must stay under the volume limit.",
        ].filter(Boolean).join("\n\n")
        // A repo the factory does not know still gets the finding, on dotfiles, with the owner named in the title.
        if (fileSignal(factory, row.owner, title, text) || fileSignal(factory, "dotfiles", `[owner ${row.owner}] ${title}`, text)) {
          filed[row.path] = { at: now.toISOString(), measured_gib: measured, cap_gib: row.cap_gib }
          signal = "filed"
          nFiled++
        } else failures++
      } else signal = "open"
    }
    console.log(`disk-budget: ${over ? "OVER" : "ok  "} ${row.path} ${fmt(measured)} / ${row.cap_gib} GiB (${row.owner}, ${row.class})${present ? "" : " absent"}${signal ? ` signal ${signal}` : ""}`)
    return { path: row.path, owner: row.owner, class: row.class, enforced_by: row.enforced_by, cap_gib: row.cap_gib, measured_gib: Number(measured.toFixed(4)), over, present, signal }
  })

  const unknown = findUnknown(sizes, budget.rows, budget.unknown_gib * KIB_PER_GIB).map(([p, kib]) => {
    const key = `unknown:${p}`
    const measured = gib(kib)
    const shown = p.startsWith(home() + "/") ? "~" + p.slice(home().length) : p
    let signal: "filed" | "open" | null = null
    keep(key)
    if (due(key)) {
      const title = `disk budget: ${shown} is ${fmt(measured)} GiB and no row covers it`
      const text = `${shown} measures ${fmt(measured)} GiB (du -xk), above the ${budget.unknown_gib} GiB line for a path outside the disk budget (config/mini/disk-budget.yaml in dotfiles, docs/disk.md). Find its owner and add a row with an owner repo, a cap and what enforces it, or remove what is growing there.`
      if (fileSignal(factory, "dotfiles", title, text)) {
        filed[key] = { at: now.toISOString(), measured_gib: measured, cap_gib: budget.unknown_gib }
        signal = "filed"
        nFiled++
      } else failures++
    } else signal = "open"
    console.log(`disk-budget: UNKNOWN ${shown} ${fmt(measured)} GiB, no row${signal ? ` signal ${signal}` : ""}`)
    return { path: p, measured_gib: Number(measured.toFixed(4)), signal }
  })

  writeAtomic(join(stateDir, "state.json"), JSON.stringify({ filed }, null, 2) + "\n")
  writeAtomic(
    join(stateDir, "status.json"),
    JSON.stringify(
      {
        at: now.toISOString(),
        volume: vol ? { path: budget.volume, size_gib: Number(vol.sizeGib.toFixed(1)), used_gib: Number(vol.usedGib.toFixed(1)), used_pct: vol.pct } : { path: budget.volume },
        commit: { caps_gib: c.caps, system_gib: c.system, total_gib: c.total, limit_gib: Number(c.limit.toFixed(1)), over_committed: overCommitted },
        rows,
        unknown,
        over: rows.filter((r) => r.over).length,
        signals_filed: nFiled,
        failures,
      },
      null,
      2,
    ) + "\n",
  )
  console.log(`disk-budget: ${rows.length} rows, ${rows.filter((r) => r.over).length} over cap, ${unknown.length} uncovered, ${nFiled} signals filed, ${failures} failures`)
  return failures > 0 ? 1 : 0
}

// ---- main ----

function main(argv: string[]): number {
  const opt = (name: string) => {
    const i = argv.indexOf(name)
    return i >= 0 ? argv[i + 1] : undefined
  }
  const file = resolve(opt("--file") ?? process.env.DISK_BUDGET_FILE ?? DEFAULT_FILE)
  const doc = resolve(opt("--doc") ?? process.env.DISK_BUDGET_DOC ?? DEFAULT_DOC)
  switch (argv[0] ?? "check") {
    case "check":
      return check(file)
    case "lint": {
      const errors = lint(file, doc)
      for (const e of errors) console.error(`disk-budget: ${e}`)
      if (!errors.length) console.log("disk-budget: table valid, under the commit limit, doc in sync")
      return errors.length ? 1 : 0
    }
    case "table": {
      const { budget, errors } = parseBudget(readFileSync(file, "utf8"))
      if (!budget) { for (const e of errors) console.error(`disk-budget: ${e}`); return 1 }
      const table = renderTable(budget)
      if (!argv.includes("--write")) { console.log(table); return 0 }
      const parts = docBlock(readFileSync(doc, "utf8"))
      if (!parts) { console.error(`disk-budget: ${doc} has no disk-budget:table block`); return 1 }
      writeFileSync(doc, `${parts.before}${BLOCK_START}\n${table}\n${BLOCK_END}${parts.after}`)
      return 0
    }
    default:
      console.error("usage: disk-budget.ts check | lint | table [--write] [--file F] [--doc D]")
      return 64
  }
}

if (import.meta.main) process.exit(main(process.argv.slice(2)))
